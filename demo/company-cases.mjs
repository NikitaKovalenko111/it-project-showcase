function makeCase(companyId, title, summary, index, kind) {
  const active = kind === 'hackathon' && index < 3
  const publishedAt = active ? '2026-11-24' : `2026-${index % 2 ? '09' : '10'}-01`
  const deadlineDate = active ? `2026-12-${12 + index * 5}` : `2026-${index % 2 ? '09' : '10'}-24`
  return {
    id: `demo:${companyId}:${kind}:${index}`,
    companyId, kind, title, shortDescription: summary,
    fullDescription: `Учебный сценарий демонстрационной витрины.\n\n${active ? '## Задача' : '## Что сделала команда'}\n\n${summary}\n\n## Проверка\n\nДанные учебные. На защите команда показывает основной сценарий, один пограничный случай и инструкцию повторного запуска.`,
    status: active ? 'open' : 'completed',
    publishedAt, deadlineDate,
    applicationDeadline: active ? `2026-12-0${3 + index}` : null,
    complexity: 'Средний', workFormat: 'смешанный', duration: kind === 'hackathon' ? '3 дня' : '3 недели',
    direction: index % 2 ? 'Бизнес-анализ' : 'Backend',
    participationFormat: 'both',
    resultRequirements: 'Рабочий прототип, инструкция запуска, пример данных и список проверенных сценариев.',
    evaluationOrder: 'Работоспособность, воспроизводимость и ясность демонстрации.',
    rewardType: kind === 'hackathon' ? 'contest' : 'educational',
  }
}

