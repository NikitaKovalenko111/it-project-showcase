 login(own.studentId)
 server.updateExecutionStage(own.id,stage.id,'submit',[{name:'prototype.txt',url:'data:text/plain,own'}])
 assert.throws(()=>server.updateExecutionStage(peer.id,peer.milestones[0].id,'submit',[{name:'x',url:'x'}]),/участникам/)
